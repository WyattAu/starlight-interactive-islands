import type { IslandComponent } from './types.js';
import type { ComponentRegistry } from './registry.js';

export function generateMDXImports(registry: ComponentRegistry): string {
  const components = registry.getAll();
  const lines: string[] = [];

  for (const component of components) {
    lines.push(`import ${component.name} from '${component.component}';`);
  }

  return lines.join('\n');
}

export function generateMDXComponents(registry: ComponentRegistry): Record<string, string> {
  const result: Record<string, string> = {};

  for (const component of registry.getAll()) {
    result[component.name] = buildIslandComponent(component);
  }

  return result;
}

function buildIslandComponent(component: IslandComponent): string {
  const directive =
    component.hydration === 'only'
      ? `client:only="${component.clientOnlyFramework ?? component.framework}"`
      : component.hydration === 'media'
        ? `client:media="${component.mediaQuery}"`
        : `client:${component.hydration}`;

  const wrapperTag = component.wrapperTag ?? 'div';
  const wrapperClass = component.wrapperClass;
  const classAttr = wrapperClass ? ` class="${wrapperClass}"` : '';

  const parts = [
    `// Auto-generated island wrapper for ${component.name}`,
    `const ${component.name}Island = ({ children, ...props }) => (`,
    `  <${wrapperTag}${classAttr}>`,
    `    <${component.name} ${directive} {...props} />`,
    `    {children}`,
    `  </${wrapperTag}>`,
    `);`,
  ];

  return parts.join('\n');
}

export function generateAstroIntegrationConfig(registry: ComponentRegistry): {
  imports: string[];
  components: Record<string, string>;
  frameworks: string[];
} {
  const imports = registry.generateImports();
  const components = generateMDXComponents(registry);
  const frameworks = Array.from(registry.getRequiredFrameworks());

  return { imports, components, frameworks };
}

export function generateGlobalTypeDeclaration(registry: ComponentRegistry): string {
  const components = registry.getAll();
  const lines: string[] = [
    '// Auto-generated by starlight-interactive-islands',
    'declare global {',
    '  namespace JSX {',
    '    interface IntrinsicElements {',
  ];

  for (const component of components) {
    lines.push(`      ${component.name}: Record<string, any>;`);
  }

  lines.push('    }');
  lines.push('  }');
  lines.push('}');
  lines.push('export {};');

  return lines.join('\n');
}
